import { DEFAULT_HANDOFF_SCHEMA } from '../spec/schema.js';

/**
 * Claude Code project settings + the deterministic handover gate.
 *
 * Two things live here, both aimed at the same problem: a generated fleet is
 * only as reliable as its weakest advisory instruction.
 *
 *  1. `.claude/settings.json` — a permission allowlist derived from what the
 *     fleet's agents actually declared, so the harness runs without stopping
 *     to ask about work it was designed to do.
 *  2. A `SubagentStop` hook per fleet agent, running a bundled validator.
 *     Hooks are the only deterministic layer available: exit 2 blocks the
 *     subagent from stopping and feeds stderr back to it. That converts "the
 *     agent should write its handoff file" from hope into a contract.
 *
 * Caveat worth knowing (and stated in the generated pointer): project-level
 * hooks stay inert until the workspace trust dialog is accepted, and they are
 * silently skipped until then.
 */

export const VALIDATOR_PATH = 'scripts/validate-handoff.sh';

/**
 * Permission allowlist. Read-family tools are always safe; write and execute
 * grants follow the agents' declared capabilities. Scoped rules are used
 * deliberately: a bare tool-name deny would drop the tool from context and
 * invalidate the prompt cache for every turn.
 */
export function settingsJson(spec, { validatorPath }) {
  const anyEdit = spec.agents.some((a) => a.capabilities.edit);
  const anyRun = spec.agents.some((a) => a.capabilities.run);
  const anyWeb = spec.agents.some((a) => a.capabilities.web);

  const allow = ['Read', 'Grep', 'Glob'];
  // Every agent writes handoffs and ledger rows, even read-only ones.
  allow.push(`Write(${spec.fleet.workspace}/**)`, `Edit(${spec.fleet.workspace}/**)`);
  if (anyEdit) allow.push('Write', 'Edit');
  if (anyRun) allow.push('Bash');
  if (anyWeb) allow.push('WebSearch', 'WebFetch');
  allow.push(`Bash(sh ${validatorPath}:*)`);

  return `${JSON.stringify(
    {
      $schema: 'https://json.schemastore.org/claude-code-settings.json',
      permissions: { allow },
      hooks: {
        SubagentStop: [
          {
            matcher: spec.agents.map((a) => a.name).join('|'),
            hooks: [
              {
                type: 'command',
                command: `sh "$CLAUDE_PROJECT_DIR/${validatorPath}"`,
                timeout: 15,
              },
            ],
          },
        ],
      },
    },
    null,
    2
  )}\n`;
}

/**
 * The gate script. Reads the hook payload on stdin, resolves which agent just
 * finished, and refuses to let it stop until its handoff artifact exists and
 * carries every required section.
 *
 * Written in POSIX sh with no dependencies beyond grep/sed so it runs wherever
 * the harness is checked out. It parses the payload with grep rather than a
 * JSON parser for the same reason — the only field needed is a flat string.
 *
 * Exit codes are the hook contract: 2 blocks the stop and sends stderr back to
 * the agent as instructions; 0 lets it finish. Anything else is non-blocking,
 * so the script must never fail open on a genuine violation.
 */
export function validatorScript(spec) {
  // Defense in depth: validateSpec already rejects unsafe paths, but this
  // value lands inside a shell script that runs on whoever installs the
  // harness, and fleet specs are meant to be shared. Quote it properly here
  // too rather than trusting that the build ran the validator first.
  const dir = shellSingleQuote(spec.handover.dir);
  // Terminal agents write no handoff file; they are checked for a ledger row.
  const terminal = spec.agents.filter((a) => a.handoff.to.length === 0).map((a) => a.name);
  const ledger = spec.handover.ledger ? shellSingleQuote(`${spec.fleet.workspace}/LEDGER.md`) : '';

  // Required sections come from the declared schema when there is one, so the
  // gate enforces the same contract the handoff template advertises.
  const sectionsFor = (agent) => {
    const schema = agent.handoff.schema ?? DEFAULT_HANDOFF_SCHEMA;
    return Object.keys(schema).map(sectionHeading).join('|');
  };
  const cases = spec.agents
    .filter((a) => a.handoff.to.length > 0)
    .map((a) => `    ${a.name}) required='${sectionsFor(a)}' ;;`)
    .join('\n');

  return `#!/bin/sh
# Handover gate for the ${spec.fleet.name} fleet (generated by fleetsmith).
#
# Runs as a Claude Code SubagentStop hook. Exit 2 blocks the subagent from
# stopping and returns stderr to it as further instructions; exit 0 accepts.
# Registered in .claude/settings.json — do not rename without updating it.
set -u

payload=$(cat 2>/dev/null || true)

# The hook payload is JSON on stdin; agent_type is a flat string field.
agent=$(printf '%s' "$payload" | sed -n 's/.*"agent_type"[[:space:]]*:[[:space:]]*"\\([^"]*\\)".*/\\1/p')
[ -n "$agent" ] || exit 0   # not a fleet subagent stop we can attribute

dir=${dir}
required=''
case "$agent" in
${cases || "    '') ;;"}
    ${terminal.length ? terminal.join('|') : '__no_terminal_agents__'})
        # Terminal agents produce the deliverable, not a handoff file.
        exit 0 ;;
    *) exit 0 ;;   # unknown agent: not ours to police
esac

# Handoff files are named {seq}-{from}-to-{receiver}.md
file=$(ls "$dir"/*-"$agent"-to-*.md 2>/dev/null | head -n 1)
if [ -z "$file" ]; then
    echo "Handover gate: no handoff file found for '$agent' in $dir/." >&2
    echo "Write $dir/{seq}-$agent-to-{receiver}.md using $dir/HANDOFF.template.md before finishing." >&2
    exit 2
fi

missing=''
old_ifs=$IFS
IFS='|'
for section in $required; do
    [ -n "$section" ] || continue
    grep -qi "^#\\{1,6\\}[[:space:]]*$section" "$file" || missing="$missing $section"
done
IFS=$old_ifs

if [ -n "$missing" ]; then
    echo "Handover gate: $file is missing required section(s):$missing" >&2
    echo "A receiver with zero shared context reads only this file — fill those sections, then finish." >&2
    exit 2
fi
${
  ledger
    ? `
if [ -f ${ledger} ] && ! grep -q "$agent" ${ledger}; then
    echo "Handover gate: '$agent' has no row in ${ledger}." >&2
    echo "Add or update your ledger row (status + artifact path) before finishing." >&2
    exit 2
fi
`
    : ''
}
exit 0
`;
}

/**
 * POSIX single-quote escaping: wrap in single quotes and close/reopen around
 * any embedded single quote. Nothing inside single quotes is interpreted by
 * the shell, so the result is inert whatever the input contains.
 */
function shellSingleQuote(value) {
  return `'${String(value).replace(/'/g, `'\\''`)}'`;
}

/** `output_format` -> `Output format`, matching the headings in the handoff template. */
function sectionHeading(field) {
  const words = String(field).replace(/[_-]+/g, ' ').trim();
  return words.charAt(0).toUpperCase() + words.slice(1);
}

/**
 * `.claude/loop.md` overrides the built-in prompt for a bare `/loop`, so a
 * scheduled fleet re-fires into its own playbook instead of generic
 * maintenance. Only emitted when the fleet declares a schedule.
 */
export function loopMd(spec) {
  const sch = spec.fleet.schedule;
  const what = sch.note || `run the ${spec.fleet.name} fleet`;
  return `# Recurring run — ${spec.fleet.name}

Each firing: ${what}

1. Invoke the \`${spec.orchestrator.name}\` skill.
2. Start with its Phase 0 context check — a recurring run must resume or refresh
   state, never clobber the previous run's workspace.
3. If there is nothing to do this firing, say so and stop; an empty pass is a
   valid outcome, and inventing work to fill it is not.

Notes for whoever schedules this:
- Recurring scheduled tasks expire after 7 days and need re-arming.
- Fire times carry deterministic jitter (up to 30 minutes for recurring tasks),
  so do not depend on running exactly on the hour.
- A skill marked \`disable-model-invocation\` cannot run from a scheduled fire.
`;
}
